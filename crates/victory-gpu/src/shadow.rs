#[cfg(all(test, feature = "diagnostics"))]
#[test]
fn warp_range_lookup_reuses_the_parent_and_the_spanning_window() {
    use windows_sys::Win32::System::Memory::{
        MEM_COMMIT, MEM_RELEASE, MEM_RESERVE, PAGE_READWRITE, VirtualAlloc, VirtualFree,
    };

    if std::env::var_os("VICTORY_D3D12_WARP").is_none() {
        return;
    }
    // Keep the fixture bounded to 12 MiB of title memory plus a few host buffers.
    let size = 12 << 20;
    // SAFETY: a test-owned reservation, released at the end.
    let base = unsafe {
        VirtualAlloc(
            std::ptr::null(),
            size,
            MEM_RESERVE | MEM_COMMIT,
            PAGE_READWRITE,
        )
    };
    assert!(!base.is_null());
    let start = base as u64;
    let parent_len = 1 << 20;
    register(1, start, parent_len);
    for i in 1..=128 {
        register(1 + i as usize, start + 4096 * i, 4096);
    }
    let parent = find(start, 16).expect("parent WARP shadow");
    let child = find(start + 4096, 16).expect("child WARP shadow");
    let far = find(start + parent_len - 16, 16).expect("far end of parent");
    for i in 1..=128 {
        unregister(1 + i as usize, start + 4096 * i);
    }
    unregister(1, start);

    // An aligned window boundary after the registered range. Both sides of
    // it lie inside the reservation.
    let boundary = (start + parent_len).next_multiple_of(WINDOW);
    let spanning = find(boundary - 16, 32).expect("two-window WARP shadow");
    let contained = find(boundary + 16, 16).expect("contained WARP shadow");
    // SAFETY: base is the reservation made above.
    assert_ne!(unsafe { VirtualFree(base, 0, MEM_RELEASE) }, 0);
    assert!(!Arc::ptr_eq(&parent, &child), "a child stays innermost");
    assert!(
        Arc::ptr_eq(&parent, &far),
        "far lookup took a separate shadow"
    );
    assert!(
        Arc::ptr_eq(&spanning, &contained),
        "contained range allocated a second window"
    );
}
